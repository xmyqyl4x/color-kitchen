import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const v3 = require('tailwindcss-v3/colors');
const oldFamilies = {};
for (const [name, property] of Object.entries(Object.getOwnPropertyDescriptors(v3))) {
  if (property.get || !property.value || !shades.every(shade => typeof property.value[shade] === 'string')) continue;
  oldFamilies[name] = shades.map(shade => property.value[shade]);
}
const modern = {};
const theme = await readFile(require.resolve('tailwindcss/theme.css'), 'utf8');
for (const match of theme.matchAll(/^\s*--color-([a-z]+)-(\d+):\s*(.+?);\s*$/gm)) {
  const [, family, shade, value] = match;
  (modern[family] ??= {})[Number(shade)] = value;
}
const newFamilies = Object.fromEntries(Object.entries(modern).map(([name, family]) => [
  name, shades.map(shade => {
    if (!family[shade]) throw new Error(`Missing Tailwind color ${name}-${shade}`);
    return family[shade];
  }),
]));
if (!Object.keys(oldFamilies).length || !Object.keys(newFamilies).length) throw new Error('Missing Tailwind color families.');
const output = '// Generated by scripts/generate-tailwind-colors.mjs from the pinned Tailwind packages.\n' +
  '// The color tables are provided under the notices in catalog/licenses/.\n' +
  'export const pinnedColors = ' + JSON.stringify({ 3: oldFamilies, 4: newFamilies }, null, 2) + ' as const;\n';
await writeFile(new URL('../src/tailwind/pinned-colors.ts', import.meta.url), output);
