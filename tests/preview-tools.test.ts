import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { compile } from 'tailwindcss';
import { webHttp } from '../src/web/http.js';
import { chooseColor, withBrowserPage } from './browser.js';
import { withHttp } from './http.js';

test('one active palette carries role IDs into templates and a pinned base into both Tailwind versions', async () => {
  const web = webHttp({ async withClient() { throw new Error('Design tools stay on the device.'); } });
  await withHttp(web, origin => withBrowserPage(async page => {
    await page.goto(origin + '/en/palette-studio');
    const swatch = page.locator('[data-control="swatch-1:value"]');
    await swatch.fill('#235982');
    await swatch.blur();
    await page.locator('#palette-role').selectOption('primary');
    await chooseColor(page, 'palette-role-color', 'swatch-1');
    assert.equal(await page.locator('#palette-role-color-trigger [data-swatch-code]').getAttribute('data-swatch-code'), '#235982');
    await page.locator('[data-control="swatch-1:options"]').click();
    await page.locator('[data-control="swatch-1:later"]').click();
    await page.locator('[data-focus-key=studio-design]').click();
    await page.locator('#template-canvas [data-block]').first().waitFor();
    const primary = page.locator('[data-preview-role=primary]');
    assert.equal(await primary.inputValue(), 'swatch-1');
    assert.equal(await page.locator('#preview-role-primary-trigger .color-chip').getAttribute('data-swatch-code'), '#235982');
    await page.locator('#preview-template').selectOption('dashboard');
    await page.locator('#preview-size').selectOption('mobile');
    assert.equal(await primary.inputValue(), 'swatch-1');
    await page.locator('[data-block=header]').click();
    assert.match(await page.locator('#preview-pair').textContent() ?? '', /#235982/);
    assert.equal(await page.locator('#preview-pair .color-token').count(), 2);
    const imageEvent = page.waitForEvent('download');
    await page.locator('#preview-export').click();
    const image = await readFile((await (await imageEvent).path())!);
    assert.equal(image.readUInt32BE(16), 360);
    assert.equal(image.readUInt32BE(20), 600);
    await page.locator('#preview-reset').click();
    assert.equal(await primary.inputValue(), '');
    await page.goto(origin + '/en/tailwind');
    await page.locator('#tw-generate').click();
    await chooseColor(page, 'tw-base', 'swatch-1');
    await page.locator('#tw-anchor').selectOption('700');
    const output = page.locator('#tw-output');
    assert.match(await page.locator('[data-shade="700"]').textContent() ?? '', /#235982/);
    assert.match(await output.inputValue(), /@theme/);
    const generated = await compile(await output.inputValue() + '\n@tailwind utilities;');
    assert.match(generated.build(['bg-kitchen-700']), /--color-kitchen-700/);
    await page.locator('#tw-version').selectOption('3');
    assert.match(await output.inputValue(), /^module.exports = /);
    assert.doesNotMatch(await output.inputValue(), /@theme/);
    await chooseColor(page, 'tw-override', '700');
    await page.locator('#tw-override-color').fill('#111');
    await page.locator('#tw-apply').click();
    assert.match(await page.locator('#preview-status').textContent() ?? '', /pinned shade/);
    await chooseColor(page, 'tw-override', '300');
    await page.locator('#tw-override-color').fill('#112233');
    await page.locator('#tw-apply').click();
    assert.match(await page.locator('[data-shade="300"]').textContent() ?? '', /#112233/);
    assert.equal(await page.locator('#tw-override-trigger .color-chip').getAttribute('data-swatch-code'), '#112233');
  }));
});

test('Tailwind Studio explores built-ins, uses a shade in examples and exports the generated scale', async () => {
  const web = webHttp({ async withClient() { throw new Error('Tailwind Studio stays on the device.'); } });
  await withHttp(web, origin => withBrowserPage(async page => {
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(origin + '/en/tailwind');
    await page.locator('[data-family="indigo"]').waitFor();
    assert.equal(await page.locator('[data-family]').count(), 26);
    assert.equal(await page.locator('[data-shade]').count(), 11);
    await page.locator('#tw-category').selectOption('blues');
    assert.equal(await page.locator('[data-family]').count(), 5);
    await page.locator('#tw-search').fill('sky');
    await page.locator('[data-family="sky"]').press('Enter');
    await page.locator('[data-shade="600"]').press('Enter');
    const selected = await page.locator('#tw-value').inputValue();
    assert.match(selected, /^oklch\(/);
    assert.match(await page.locator('#tw-examples').textContent() ?? '', /bg-sky-600/);
    await page.locator('#tw-theme').selectOption('dark');
    assert.match(await page.locator('#tw-examples').textContent() ?? '', /bg-sky-900 text-sky-100/);
    await page.locator('#tw-utility').selectOption('border');
    await page.locator('#tw-copy-class').click();
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'border-sky-600');
    const popup = page.waitForEvent('popup');
    await page.locator('#tw-inspect').click();
    const inspector = await popup;
    await inspector.waitForURL('**/color-inspector#color=*');
    assert.equal(decodeURIComponent(new URL(inspector.url()).hash.slice(7)), selected);
    await inspector.close();

    await page.locator('#tw-format').selectOption('json');
    const file = page.waitForEvent('download');
    await page.locator('#tw-download').click();
    const downloaded = await file;
    assert.equal(downloaded.suggestedFilename(), 'sky.json');
    assert.equal(JSON.parse(await readFile((await downloaded.path())!, 'utf8')).sky[600], selected);

    await page.locator('#tw-from-shade').click();
    assert.equal(await page.locator('#tw-base-color').inputValue(), selected);
    assert.equal(await page.locator('#tw-anchor').inputValue(), '600');
    assert.equal(await page.locator('#tw-shade-title').textContent(), 'sky-custom-600');
    assert.match(await page.locator('#tw-output').inputValue(), /@theme \{\n  --color-sky-custom-50:/);
    const theme = await compile(await page.locator('#tw-output').inputValue() + '\n@tailwind utilities;');
    assert.match(theme.build(['border-sky-custom-600']), /border-color: var\(--color-sky-custom-600\)/);
    await page.locator('#tw-base-color').fill('invalid');
    await page.locator('#tw-base-color').blur();
    assert(await page.locator('#tw-details').isHidden());
    assert.equal(await page.locator('#tw-output').inputValue(), '');
    await page.locator('#tw-base-color').fill('#005E52');
    await page.locator('#tw-base-color').blur();
    assert.match(await page.locator('[data-shade="600"]').textContent() ?? '', /#005E52/);
    await page.locator('#tw-version').selectOption('3');
    assert.match(await page.locator('#tw-output').inputValue(), /^module.exports/);
    await page.locator('#tw-browse').click();
    await page.locator('#tw-search').fill('');
    await page.locator('#tw-category').selectOption('all');
    assert.equal(await page.locator('[data-family]').count(), 22);
    assert.match(await page.locator('#tw-value').inputValue(), /^#[0-9a-f]{6}$/);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  }));
});
